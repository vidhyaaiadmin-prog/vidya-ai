'use client';
import { useState, useEffect, useCallback } from 'react';
import { useRouter } from 'next/navigation';
import { Building2, Download, FileText, LogOut, Plus, Users, TrendingUp } from 'lucide-react';
import { Button, Card, Badge, Input, Textarea } from '@/components/ui';
import { useUserStore } from '@/lib/stores';
import { performLogout } from '@/lib/logout';
import { authFetch } from '@/lib/api-client';
import toast from 'react-hot-toast';

const COMPLIANCE_PACK = `VIDYA AI — INSTITUTIONAL COMPLIANCE SUMMARY

1. DATA RESIDENCY & PRIVACY (DPDPA 2023)
   - All student data is stored in Supabase (Postgres) with row-level security enforced per user.
   - Access to any student's data requires their own authenticated session, or institution-admin
     access scoped strictly to that institution's own students.
   - No student data is shared across institutions or with third parties beyond the AI providers
     (Google Gemini, Anthropic Claude) strictly necessary to generate a response.

2. DATA PORTABILITY
   - Institutions may export their full student dataset at any time via the Admin Console —
     no support ticket or notice period required.
   - On non-renewal, the institution retains this export right for 90 days before deletion.

3. AI COST & USAGE CONTROL
   - Every AI call is logged per student with token counts and cost, auditable per institution.
   - A flat daily per-student token allowance prevents runaway usage from affecting billing.

4. SECURITY PRACTICES
   - Passwords and sessions are managed by Supabase Auth (industry-standard, not custom-built).
   - All API routes require authentication; rate limiting is enforced per IP and per feature.
   - Security headers (CSP, HSTS, X-Frame-Options) are enforced on every response.

5. SLA
   - Target uptime and support response times are defined in the institution's signed contract,
     not in this general document. Contact your Vidya AI account contact for specifics.

Generated by Vidya AI Admin Console. Not a substitute for a signed Data Processing Agreement —
request the DPA template from your account contact for execution.`;

function download(filename: string, content: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename; a.click();
  URL.revokeObjectURL(url);
}

export default function AdminPage() {
  const router = useRouter();
  const { user } = useUserStore();
  const [overview, setOverview] = useState<any>(null);
  const [entries, setEntries] = useState<any[]>([]);
  const [criterion, setCriterion] = useState('');
  const [note, setNote] = useState('');
  const [loading, setLoading] = useState(true);

  const loadIqac = useCallback(async () => {
    const res = await authFetch('/api/admin/iqac', { action: 'list' });
    const data = await res.json();
    setEntries(data.entries ?? []);
  }, []);

  useEffect(() => {
    (async () => {
      const res = await authFetch('/api/admin/overview', {});
      if (res.status === 403) {
        toast.error('Institution admin access required.');
        router.push('/home');
        return;
      }
      setOverview(await res.json());
      await loadIqac();
      setLoading(false);
    })();
  }, [router, loadIqac]);

  const exportData = async () => {
    const res = await authFetch('/api/admin/export', {});
    const data = await res.json();
    download(`vidya-ai-export-${Date.now()}.json`, JSON.stringify(data, null, 2), 'application/json');
    toast.success('Export downloaded.');
  };

  const addEvidence = async () => {
    if (!criterion.trim() || !note.trim()) return;
    await authFetch('/api/admin/iqac', { action: 'add', criterion, note });
    setCriterion(''); setNote('');
    await loadIqac();
    toast.success('Evidence logged.');
  };

  const logout = () => { performLogout(); };

  if (loading) return <div className="min-h-screen bg-navy flex items-center justify-center text-text-tertiary text-sm">Loading admin console…</div>;

  const inst = overview?.institution;

  return (
    <div className="min-h-screen bg-navy">
      <header className="flex items-center justify-between px-6 py-4 border-b border-card-border">
        <div className="flex items-center gap-2">
          <Building2 className="w-5 h-5 text-orange" />
          <span className="font-display font-bold text-lg text-text-primary">Institution Admin Console</span>
        </div>
        <Button variant="ghost" size="sm" icon={<LogOut className="w-4 h-4" />} onClick={logout}>Sign Out</Button>
      </header>

      <div className="max-w-3xl mx-auto p-6 space-y-6">
        {/* Overview */}
        <Card>
          <div className="flex items-center justify-between mb-4">
            <h2 className="font-display font-bold text-lg text-text-primary">{inst?.name ?? 'Your Institution'}</h2>
            <Badge color={inst?.is_active ? 'mint' : 'danger'}>{inst?.is_active ? 'Active' : 'Inactive'}</Badge>
          </div>
          <div className="grid grid-cols-3 gap-3">
            <div className="stat-card">
              <div className="font-display font-bold text-xl text-orange">{overview?.seatsUsed ?? 0}/{inst?.seats_limit ?? '—'}</div>
              <div className="text-xs text-text-secondary">Seats Used</div>
            </div>
            <div className="stat-card">
              <div className="font-display font-bold text-xl text-violet">{overview?.avgXp ?? 0}</div>
              <div className="text-xs text-text-secondary">Avg Student XP</div>
            </div>
            <div className="stat-card">
              <div className="font-display font-bold text-xl text-teal">{overview?.activeWeek ?? 0}</div>
              <div className="text-xs text-text-secondary">Active This Week</div>
            </div>
          </div>
          {inst?.contract_end && (
            <p className="text-xs text-text-tertiary mt-3">Contract through {new Date(inst.contract_end).toLocaleDateString()}</p>
          )}
        </Card>

        {/* Data export + compliance */}
        <div className="grid grid-cols-2 gap-4">
          <Card className="flex flex-col gap-2">
            <div className="flex items-center gap-2"><Download className="w-4 h-4 text-orange" /><span className="text-sm font-semibold text-text-primary">Data Export</span></div>
            <p className="text-xs text-text-tertiary">Full student + progress data, any time — no ticket needed.</p>
            <Button size="sm" variant="secondary" onClick={exportData}>Download JSON</Button>
          </Card>
          <Card className="flex flex-col gap-2">
            <div className="flex items-center gap-2"><FileText className="w-4 h-4 text-violet-light" /><span className="text-sm font-semibold text-text-primary">Compliance Pack</span></div>
            <p className="text-xs text-text-tertiary">DPDPA, security, and SLA summary for procurement.</p>
            <Button size="sm" variant="secondary" onClick={() => download('vidya-ai-compliance-pack.txt', COMPLIANCE_PACK, 'text/plain')}>Download</Button>
          </Card>
        </div>

        {/* IQAC evidence vault */}
        <Card>
          <div className="flex items-center gap-2 mb-3">
            <Users className="w-4 h-4 text-teal" />
            <span className="text-sm font-semibold text-text-primary">IQAC Evidence Vault</span>
          </div>
          <div className="space-y-2 mb-4">
            <Input value={criterion} onChange={e => setCriterion(e.target.value)} placeholder="NAAC Criterion (e.g. Criterion II — Teaching-Learning)" />
            <Textarea value={note} onChange={e => setNote(e.target.value)} placeholder="Evidence note…" rows={2} />
            <Button size="sm" icon={<Plus className="w-4 h-4" />} onClick={addEvidence} disabled={!criterion.trim() || !note.trim()}>Log Evidence</Button>
          </div>
          <div className="space-y-2">
            {entries.map(e => (
              <div key={e.id} className="p-3 rounded-lg bg-card-light border border-card-border">
                <Badge color="grey" className="mb-1">{e.criterion}</Badge>
                <p className="text-xs text-text-secondary">{e.note}</p>
              </div>
            ))}
            {entries.length === 0 && <p className="text-xs text-text-tertiary">No evidence logged yet.</p>}
          </div>
        </Card>

        <p className="text-[10px] text-text-tertiary flex items-center gap-1.5">
          <TrendingUp className="w-3 h-3" /> Multi-campus hierarchy and faculty onboarding tracks are planned but not yet built.
        </p>
      </div>
    </div>
  );
}
